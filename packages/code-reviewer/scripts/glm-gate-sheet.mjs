// Hand-read sheet and resolver for change `finder-glm-5-3-high`, built by
// change `finder-glm-5-3` (its plan.md Phase 3 §3; owner decision 1). Every
// published finding of every valid #247 and #269
// run gets one row — no cross-run deduplication — and the OWNER classifies
// it. The agent may pre-flag a D2 candidate; it never classifies.
//
// D2 comes from the ledger (this change's plan.md Phase 2 §3; owner decision
// 2026-10-16 (a)): each #269 run's `d2` line is final, the sheet pre-fills
// `D2` on the findings it approved, and `resolve` takes the D2 count from the
// ledger, flagging any sheet that disagrees. The full hand-read does not
// revisit D2.
//
// Subcommands (from packages/code-reviewer):
//   node scripts/glm-gate-sheet.mjs sheet   [--dry-run --series <jsonl> --results <dir> --out-dir <dir>]
//   node scripts/glm-gate-sheet.mjs resolve [--dry-run --series <jsonl> --results <dir> --sheets-dir <dir>] [--out <json>]
//
// `sheet` writes hand-read-247.md and hand-read-269.md. `resolve` reads the
// owner's verdicts — `accept`, `reject`; `D2` is the ledger's — and computes
// each run's pass: rejected ≤ ceil(0.05 × N), plus, for #269, at least one
// finding approved as a D2 match. A blank or any other verdict is unresolved
// and counts as rejected. The findings themselves are read back from the
// stored review.json copies (each checked against its recorded sha256), never
// from the sheet, so a reformatted sheet cannot change what is being judged.
//
// The path flags work only with `--dry-run` (Amendment 1 as code, this
// change's plan.md H8), and a dry run refuses to write into the change folder.
//
// Exit codes: 0 done (`resolve`: every run passes), 1 a run fails or the
// inputs disagree, 2 usage or refusal.
import { createHash } from "node:crypto";
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { isD2Candidate } from "./glm-gate-core.mjs";

const PACKAGE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REPO_ROOT = resolve(PACKAGE_DIR, "..", "..");
const CHANGE_DIR = join(REPO_ROOT, "context", "changes", "finder-glm-5-3-high");

export const SHEET_CASES = Object.freeze({
  pr247: { pr: "247", file: "hand-read-247.md", d2: false },
  pr269: { pr: "269", file: "hand-read-269.md", d2: true },
});

export const VERDICTS = Object.freeze(["accept", "reject", "D2"]);

export const sha256 = (data) => createHash("sha256").update(data).digest("hex");

/** At most this many findings of a run may be rejected (§ Definitions, "run passes hand-read"). */
export const allowedRejections = (n) => Math.ceil(0.05 * n);

const location = (finding) => {
  const { file, startLine, endLine } = finding;
  if (startLine === undefined) return file;
  return endLine === undefined || endLine === startLine
    ? `${file}:${String(startLine)}`
    : `${file}:${String(startLine)}-${String(endLine)}`;
};

const cell = (text) => String(text).replaceAll("\\", "\\\\").replaceAll("|", "\\|").replaceAll("\n", " ");

/** A code fence longer than any backtick run in the text, so the text stays verbatim. */
const fence = (text) => {
  const longest = Math.max(2, ...[...String(text).matchAll(/`+/gu)].map((match) => match[0].length));
  return "`".repeat(longest + 1);
};

const verbatim = (text) => {
  const marker = fence(text);
  return [`${marker}text`, String(text), marker];
};

/**
 * The owner's D2 lines of a ledger, by run: `Map<stepId, d2 line>`. A run has
 * at most one (the runner refuses a second).
 */
export const ledgerD2Of = (series) =>
  new Map(series.filter((line) => line.type === "d2").map((line) => [line.stepId, line]));

/** The finding ids the ledger approved as D2 matches for a run. */
const approvedD2 = (ledgerD2, stepId) => {
  const line = ledgerD2.get(stepId);
  return new Set(line?.decision === "match" && Array.isArray(line.matches) ? line.matches : []);
};

/**
 * The sheet for one case. `runs` are the case's VALID runs, in series order:
 * `{ stepId, reviewSha256, findings }`. On #269, the Verdict cell of every
 * finding the ledger approved is pre-filled `D2`. The trailer records the
 * sha256 of every line above it, as generated.
 */
export function buildSheet(caseKey, runs, { at, source = "gate/series.jsonl", ledgerD2 = new Map() }) {
  const spec = SHEET_CASES[caseKey];
  const lines = [
    `# Hand-read — PR #${spec.pr}`,
    "",
    `Generated by \`scripts/glm-gate-sheet.mjs sheet\` at ${at} from \`${source}\`: every published finding of`,
    "every valid run, one row each, no deduplication across runs (owner decision 1).",
    "",
    ...(spec.d2
      ? [
          "Fill the **Verdict** cell of every empty row with `accept` (identifies a real defect in this PR's diff at its",
          "head) or `reject`. A blank or any other value is unresolved and counts as rejected.",
          "",
          "Rows pre-filled `D2` are DECIDED: they are the owner's D2 decisions, recorded per run in the ledger's `d2` lines",
          "(owner decision 2026-10-16 (a)) and final — the hand-read does not revisit them, and `resolve` flags a sheet",
          "that changes one or adds another. A run passes when rejected ≤ ceil(0.05 × N) and the ledger approved at least",
          "one D2 match. `D2?` in Flags is the agent's pre-flag (the finding matches a D2 term); it decides nothing.",
        ]
      : [
          "Fill the **Verdict** cell of every row with `accept` (identifies a real defect in this PR's diff at its head),",
          "`reject`. A blank or any other value is",
          "unresolved and counts as rejected. A run passes when rejected ≤ ceil(0.05 × N).",
        ]),
    "",
    "## Runs",
    "",
    "| Run | N | Allowed rejections | review.json sha256 |",
    "| --- | --- | --- | --- |",
    ...runs.map(
      (run) =>
        `| ${run.stepId} | ${String(run.findings.length)} | ${String(allowedRejections(run.findings.length))} | \`${run.reviewSha256}\` |`,
    ),
    "",
    "## Verdicts",
    "",
    "| Finding | Severity | Category | Location | Flags | Verdict |",
    "| --- | --- | --- | --- | --- | --- |",
  ];
  for (const run of runs) {
    const approved = spec.d2 ? approvedD2(ledgerD2, run.stepId) : new Set();
    for (const finding of run.findings) {
      const flags = spec.d2 && isD2Candidate(finding) ? "D2?" : "";
      const verdict = approved.has(finding.id) ? " D2 " : " ";
      lines.push(
        `| ${run.stepId}#${finding.id} | ${cell(finding.severity)} | ${cell(finding.category)} | \`${cell(location(finding))}\` | ${flags} |${verdict}|`,
      );
    }
  }
  lines.push("", "## Findings, verbatim", "");
  for (const run of runs) {
    for (const finding of run.findings) {
      lines.push(
        `### ${run.stepId}#${finding.id}`,
        "",
        `\`${location(finding)}\` · ${finding.severity} · ${finding.category}`,
        "",
        "Description:",
        "",
        ...verbatim(finding.description),
        "",
        "Suggestion:",
        "",
        ...verbatim(finding.suggestion),
        "",
      );
    }
  }
  const body = `${lines.join("\n").replace(/\n+$/u, "")}\n`;
  return `${body}\n<!-- generated sha256 of every line above this one: ${sha256(body)} -->\n`;
}

const splitRow = (line) =>
  line
    .trim()
    .replace(/^\|/u, "")
    .replace(/\|$/u, "")
    .split(/(?<!\\)\|/u)
    .map((part) => part.trim());

/** The owner's verdicts: `Map<findingId, verdict>` from the Verdicts table. Tolerant of reformatting. */
export function parseVerdicts(markdown) {
  const verdicts = new Map();
  const duplicates = [];
  for (const line of markdown.split("\n")) {
    if (!line.trim().startsWith("|")) continue;
    const cells = splitRow(line);
    if (cells.length !== 6 || !/^[a-z0-9-]+#F\d+$/u.test(cells[0])) continue;
    if (verdicts.has(cells[0])) duplicates.push(cells[0]);
    verdicts.set(cells[0], cells[5]);
  }
  return { verdicts, duplicates };
}

/**
 * Per-run hand-read results for one case. `runs` carry the findings read back
 * from the stored review.json copies; `verdicts` come from the sheet;
 * `ledgerD2` holds the owner's `d2` lines. On #269 a finding is `D2` exactly
 * when the ledger approved it: a sheet `D2` the ledger did not approve, or an
 * approved row the sheet calls anything else, is a problem.
 */
export function resolveCase(caseKey, runs, { verdicts, duplicates }, { ledgerD2 = new Map() } = {}) {
  const spec = SHEET_CASES[caseKey];
  const problems = duplicates.map((id) => `${id} appears more than once in the sheet`);
  const expected = new Set(runs.flatMap((run) => run.findings.map((finding) => `${run.stepId}#${finding.id}`)));
  for (const id of verdicts.keys())
    if (!expected.has(id)) problems.push(`${id} is not a published finding of a valid run`);
  const results = runs.map((run) => {
    if (spec.d2 && !ledgerD2.has(run.stepId)) problems.push(`${run.stepId}: no D2 decision in the ledger`);
    const approved = spec.d2 ? approvedD2(ledgerD2, run.stepId) : new Set();
    const rows = run.findings.map((finding) => {
      const id = `${run.stepId}#${finding.id}`;
      const raw = verdicts.get(id);
      if (raw === undefined) problems.push(`${id} is missing from the sheet`);
      if (approved.has(finding.id)) {
        if (raw !== "D2")
          problems.push(`${id} is approved as D2 in the ledger, but the sheet says ${raw ? `\`${raw}\`` : "nothing"}`);
        return { id, verdict: "D2" };
      }
      if (spec.d2 && raw === "D2") problems.push(`${id} is D2 in the sheet, but the ledger approved no such match`);
      const verdict = VERDICTS.includes(raw) && raw !== "D2" ? raw : "unresolved";
      return { id, verdict };
    });
    const n = rows.length;
    const rejected = rows.filter((row) => row.verdict === "reject" || row.verdict === "unresolved").length;
    const d2 = rows.filter((row) => row.verdict === "D2").length;
    const allowed = allowedRejections(n);
    const pass = rejected <= allowed && (!spec.d2 || d2 >= 1);
    return {
      stepId: run.stepId,
      reviewSha256: run.reviewSha256,
      n,
      rejected,
      unresolved: rows.filter((row) => row.verdict === "unresolved").length,
      allowed,
      d2,
      pass,
    };
  });
  return { results, problems };
}

// --- I/O ---------------------------------------------------------------------------

const readSeries = (path) =>
  existsSync(path)
    ? readFileSync(path, "utf8")
        .split("\n")
        .filter((line) => line.trim() !== "")
        .map((line) => JSON.parse(line))
    : [];

/** The valid runs of a case with their findings read back from the stored copies, each checked against its sha256. */
export function loadValidRuns(series, caseKey, resultsDir) {
  const problems = [];
  const runs = series
    .filter((line) => line.type === "record" && line.kind === caseKey && line.valid === true)
    .map((record) => {
      const path = join(resultsDir, `${record.stepId}.review.json`);
      if (!existsSync(path)) {
        problems.push(`${record.stepId}: stored review.json missing`);
        return { stepId: record.stepId, reviewSha256: record.reviewSha256, findings: [] };
      }
      const bytes = readFileSync(path);
      if (sha256(bytes) !== record.reviewSha256)
        problems.push(`${record.stepId}: stored review.json differs from its recorded sha256`);
      return {
        stepId: record.stepId,
        reviewSha256: record.reviewSha256,
        findings: JSON.parse(bytes.toString("utf8")).findings,
      };
    });
  return { runs, problems };
}

function parseFlags(argv) {
  const flags = {};
  for (let i = 0; i < argv.length; i += 1) {
    if (!argv[i]?.startsWith("--")) return undefined;
    if (argv[i] === "--dry-run") {
      flags["dry-run"] = true;
      continue;
    }
    if (argv[i + 1] === undefined) return undefined;
    flags[argv[i].slice(2)] = argv[i + 1];
    i += 1;
  }
  return flags;
}

/** Path overrides: a dry run's, never the hand-read's (Amendment 1 as code, this change's plan.md H8). */
const PATH_FLAGS = Object.freeze(["series", "results", "out-dir", "sheets-dir"]);

const insideChange = (path) => path === CHANGE_DIR || path.startsWith(`${CHANGE_DIR}${sep}`);

export function main(argv, { log = console.log, now = () => new Date() } = {}) {
  const [command, ...rest] = argv;
  const flags = parseFlags(rest);
  if (flags === undefined || (command !== "sheet" && command !== "resolve")) {
    log(
      "usage: glm-gate-sheet.mjs sheet|resolve [--dry-run --series <jsonl> --results <dir> --out-dir|--sheets-dir <dir>] [--out <json>]",
    );
    return 2;
  }
  const dryRun = flags["dry-run"] === true;
  const overridden = PATH_FLAGS.filter((name) => flags[name] !== undefined);
  if (overridden.length > 0 && !dryRun) {
    log(
      `REFUSED (path override without --dry-run): ${overridden.map((name) => `--${name}`).join(", ")} — the hand-read uses the change folder's own paths: drop the flag, or add --dry-run for a smoke test.`,
    );
    return 2;
  }
  const seriesPath = resolve(flags.series ?? join(CHANGE_DIR, "gate", "series.jsonl"));
  const resultsDir = resolve(flags.results ?? join(CHANGE_DIR, "gate", "results"));
  const outDir = resolve(flags["out-dir"] ?? CHANGE_DIR);
  if (dryRun) {
    // A dry run writes nothing into the change folder: not the sheets, not a series line, not a result.
    const writes =
      command === "sheet"
        ? [
            ["--out-dir", outDir],
            ["--series", seriesPath],
          ]
        : flags.out === undefined
          ? []
          : [["--out", resolve(flags.out)]];
    const inside = writes.filter(([, path]) => insideChange(path)).map(([flag]) => flag);
    if (inside.length > 0) {
      log(
        `REFUSED (dry run writing into the change folder): ${inside.join(", ")} — a dry run writes outside context/changes/finder-glm-5-3-high/: point it at a scratch directory.`,
      );
      return 2;
    }
  }
  const series = readSeries(seriesPath);
  const ledgerD2 = ledgerD2Of(series);

  if (command === "sheet") {
    mkdirSync(outDir, { recursive: true });
    const at = now().toISOString();
    // Named relative to the repository; a series outside it (a dry run) is named as such, never by its absolute path.
    const inRepo = seriesPath.startsWith(`${REPO_ROOT}/`);
    const source = inRepo ? seriesPath.slice(REPO_ROOT.length + 1) : "a series outside the repository (dry run)";
    let problems = [];
    for (const caseKey of Object.keys(SHEET_CASES)) {
      const loaded = loadValidRuns(series, caseKey, resultsDir);
      problems = [...problems, ...loaded.problems];
      const sheet = buildSheet(caseKey, loaded.runs, { at, source, ledgerD2 });
      const path = join(outDir, SHEET_CASES[caseKey].file);
      writeFileSync(path, sheet);
      const digest = sha256(sheet);
      appendFileSync(seriesPath, `${JSON.stringify({ type: "sheet", kind: caseKey, at, sha256: digest })}\n`);
      const findings = loaded.runs.reduce((sum, run) => sum + run.findings.length, 0);
      log(
        `SHEET WRITTEN: ${SHEET_CASES[caseKey].file} — ${String(loaded.runs.length)} valid run(s), ${String(findings)} finding(s), sha256 ${digest}.`,
      );
    }
    for (const problem of problems) log(`PROBLEM: ${problem}`);
    return problems.length === 0 ? 0 : 1;
  }

  const sheetsDir = resolve(flags["sheets-dir"] ?? CHANGE_DIR);
  const output = { at: now().toISOString(), cases: {}, problems: [] };
  for (const caseKey of Object.keys(SHEET_CASES)) {
    const loaded = loadValidRuns(series, caseKey, resultsDir);
    const sheetPath = join(sheetsDir, SHEET_CASES[caseKey].file);
    if (!existsSync(sheetPath)) {
      output.problems.push(`${SHEET_CASES[caseKey].file} missing — run \`sheet\` first`);
      continue;
    }
    const resolved = resolveCase(caseKey, loaded.runs, parseVerdicts(readFileSync(sheetPath, "utf8")), { ledgerD2 });
    output.cases[caseKey] = resolved.results;
    output.problems.push(...loaded.problems, ...resolved.problems);
  }
  const all = Object.values(output.cases).flat();
  output.pass = output.problems.length === 0 && all.every((run) => run.pass);
  if (flags.out !== undefined) writeFileSync(resolve(flags.out), `${JSON.stringify(output, null, 2)}\n`);
  for (const run of all) {
    log(
      `${run.stepId}: N=${String(run.n)} rejected=${String(run.rejected)} (unresolved ${String(run.unresolved)}) allowed=${String(run.allowed)}` +
        `${run.stepId.startsWith("pr269") ? ` D2=${String(run.d2)}` : ""} → ${run.pass ? "PASS" : "FAIL"}`,
    );
  }
  for (const problem of output.problems) log(`PROBLEM: ${problem}`);
  log(`HAND-READ: ${output.pass ? "PASS" : "FAIL"}`);
  return output.pass ? 0 : 1;
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main(process.argv.slice(2));
}
